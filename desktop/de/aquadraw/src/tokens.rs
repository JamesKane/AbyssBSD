    /// A token's index by the name a theme file uses for it.
    pub fn color_index(name: &str) -> Option<usize> {
        COLOR_KEYS.iter().position(|k| *k == name)
    }

    pub fn metric_index(name: &str) -> Option<usize> {
        METRIC_KEYS.iter().position(|k| *k == name)
    }

    pub fn font_index(name: &str) -> Option<usize> {
        FONT_KEYS.iter().position(|k| *k == name)
    }

    pub fn color_named(&self, name: &str) -> Option<Color> {
        ThemeTokens::color_index(name).map(|i| self.color(i))
    }

    pub fn metric_named(&self, name: &str) -> Option<f64> {
        ThemeTokens::metric_index(name).map(|i| self.metric(i))
    }
