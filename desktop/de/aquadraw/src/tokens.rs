//! Every token a theme sets (PHASE11 P11.2), converted from Theme.swift's
//! ThemeTokens. The defaults are Jaguar's, the compiled fallback, used only
//! when no theme file can be read (and said out loud when they are). The
//! shipped Aqua theme states the same values as data, and a test holds the
//! two equal. A file reaches a field only through its name in the key
//! tables, so a misspelt name is an error, not a no-op; the tables' order is
//! the index a draw list's token resolves to.

