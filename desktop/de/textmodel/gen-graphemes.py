#!/usr/bin/env python3
"""Generate de/textmodel/src/grapheme_tables.rs from the Unicode Character
Database: what UAX #29's extended grapheme clusters need to know of each
code point (Grapheme_Cluster_Break, Extended_Pictographic, Indic_Conjunct_Break).

The crate depends on nothing (RUST.md §6.5), so the tables are generated, not
a dependency. Run it when the UCD moves, and commit the output:

    python3 -I de/textmodel/gen-graphemes.py [/usr/share/unicode/ucd]

Fedora's `unicode-ucd` package installs the database where this looks by
default. The data is © Unicode, Inc., under the Unicode License v3.
"""

import re
import sys
from pathlib import Path

UCD = Path(sys.argv[1] if len(sys.argv) > 1 else "/usr/share/unicode/ucd")
OUT = Path(__file__).resolve().parent / "src" / "grapheme_tables.rs"

# The low four bits: Grapheme_Cluster_Break. Order matches `Gcb` in grapheme.rs.
GCB = ["Other", "CR", "LF", "Control", "Extend", "ZWJ", "Regional_Indicator", "Prepend",
       "SpacingMark", "L", "V", "T", "LV", "LVT"]
# The high bits: flags.
EXT_PICT, INCB_CONSONANT, INCB_LINKER, INCB_EXTEND = 0x10, 0x20, 0x40, 0x80

LINE = re.compile(r"^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*([A-Za-z_]+)(?:\s*;\s*([A-Za-z_]+))?")


def ranges(path):
    for raw in path.read_text(encoding="utf-8").splitlines():
        m = LINE.match(raw)
        if m:
            lo = int(m[1], 16)
            yield lo, int(m[2], 16) if m[2] else lo, m[3], m[4]


def version(path):
    first = path.read_text(encoding="utf-8").splitlines()[0]
    return first.lstrip("# ").strip()


value = [0] * 0x110000
for lo, hi, prop, _ in ranges(UCD / "auxiliary" / "GraphemeBreakProperty.txt"):
    for c in range(lo, hi + 1):
        value[c] = GCB.index(prop)
for lo, hi, prop, _ in ranges(UCD / "emoji" / "emoji-data.txt"):
    if prop == "Extended_Pictographic":
        for c in range(lo, hi + 1):
            value[c] |= EXT_PICT
incb = {"Consonant": INCB_CONSONANT, "Linker": INCB_LINKER, "Extend": INCB_EXTEND}
for lo, hi, prop, sub in ranges(UCD / "DerivedCoreProperties.txt"):
    if prop == "InCB":
        for c in range(lo, hi + 1):
            value[c] |= incb[sub]

# Runs of one value, leaving out the default (Other, no flags).
runs = []
start = 0
for c in range(1, 0x110001):
    if c == 0x110000 or value[c] != value[start]:
        if value[start]:
            runs.append((start, c - 1, value[start]))
        start = c

with OUT.open("w", encoding="utf-8") as f:
    f.write("// Generated by gen-graphemes.py from the Unicode Character Database\n")
    f.write(f"// ({version(UCD / 'auxiliary' / 'GraphemeBreakProperty.txt')}). Do not edit.\n")
    f.write("// The data is © Unicode, Inc., under the Unicode License v3.\n\n")
    f.write("/// (first, last, value): Grapheme_Cluster_Break in the low four bits,\n")
    f.write("/// then Extended_Pictographic, InCB=Consonant, InCB=Linker, InCB=Extend.\n")
    f.write("/// Sorted, disjoint; a code point in none is Other with no flags.\n")
    f.write("#[rustfmt::skip]\n")
    f.write(f"pub(crate) static TABLE: [(u32, u32, u8); {len(runs)}] = [\n")
    for i in range(0, len(runs), 4):
        f.write("    " + " ".join(f"(0x{a:X}, 0x{b:X}, 0x{v:02X})," for a, b, v in runs[i:i + 4]) + "\n")
    f.write("];\n")
print(f"{OUT}: {len(runs)} ranges")
